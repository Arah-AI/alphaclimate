def hazus_flood_curves() -> list[dict]:
    import openpyxl

    path = fetch("HazusFloodDamageFunctions_Hazus61.xlsx")
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)

    occ_cat = {}
    for r in wb["OccupancyTypes"].iter_rows(min_row=2, values_only=True):
        occ_cat[str(r[0]).strip()] = (str(r[1]).strip(), str(r[2]).strip())

    out = []
    sheets = [
        ("flBldgStrucDmgFn", "structure", "Hazus 6.1 flBldgStrucDmgFn"),
        ("flBldgContDmgFunc", "contents", "Hazus 6.1 flBldgContDmgFunc"),
    ]
    for sheet, basis, table in sheets:
        rows = list(wb[sheet].iter_rows(values_only=True))
        hdr = list(rows[0])
        i0, i1 = hdr.index("ft04m"), hdr.index("ft24") + 1
        depths_ft = [_depth_ft(h) for h in hdr[i0:i1]]
        x = [round(d * FT_TO_M, 4) for d in depths_ft]
        for r in rows[1:]:
            if str(r[1]).strip() in ("None", "", "NULL"):  # keep Hazus default functions only
                continue
            fn_id = int(r[0])
            occ = str(r[2]).strip()
            src = str(r[3]).strip()
            desc = str(r[4]).strip()
            y = [round(float(v) / 100.0, 4) for v in r[i0:i1]]
            cat, cat_desc = occ_cat.get(occ, ("Unknown", occ))
            out.append(
                {
                    "id": f"hazus_flood_{occ.lower()}_{basis}_{fn_id}",
                    "hazard": "flood",
                    "sub_hazard": "inundation",
                    "region": "North America",
                    "country": "United States",
                    "occupancy": cat,
                    "occupancy_detail": f"{occ} ({cat_desc}) - {desc}",
                    "damage_basis": basis,
                    "x_units": "m_depth_above_first_floor",
                    "x": x,
                    "y": y,
                    "source": (
                        f"FEMA Hazus 6.1 Flood Model, {table}, "
                        f"damage function id {fn_id} (originating source: {src})"
                    ),
                    "source_note": (
                        "Hazus default function. Depths are relative to the top of the "
                        "first finished floor, not ground level; negative depths apply to "
                        "basements. US-calibrated."
                    ),
                    "confidence": "high",
                    "calibration_range": [min(x), max(x)],
                }
            )
    wb.close()
    return out


def _depth_ft(col: str) -> float:
    """'ft04m' -> -4.0, 'ft00' -> 0.0, 'ft24' -> 24.0."""
    body = col[2:]
    if body.endswith("m"):
        return -float(body[:-1])
    return float(body)


