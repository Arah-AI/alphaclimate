def demo(doc: dict | None = None) -> dict:
    """Assert the dataset is well formed. Returns a small summary dict."""
    if doc is None:
        doc = json.loads(OUT.read_text())

    curves = doc["curves"]
    assert curves, "no curves at all"

    seen_ids = set()
    for c in curves:
        cid = c["id"]
        assert cid not in seen_ids, f"duplicate id {cid}"
        seen_ids.add(cid)

        x, y = c["x"], c["y"]
        assert x, f"{cid}: empty x"
        assert y, f"{cid}: empty y"
        assert len(x) == len(y), f"{cid}: x/y length mismatch {len(x)} vs {len(y)}"
        assert all(b > a for a, b in zip(x, x[1:])), f"{cid}: x not strictly ascending"
        assert all(0.0 <= v <= 1.0 for v in y), (
            f"{cid}: y outside [0,1] -> min {min(y)} max {max(y)}"
        )
        assert all(b >= a - 1e-9 for a, b in zip(y, y[1:])), (
            f"{cid}: y not monotonically non-decreasing"
        )

        assert c["source"] and len(c["source"]) > 20, f"{cid}: source too thin"
        assert c["confidence"] in ("high", "medium", "low"), f"{cid}: bad confidence"
        lo, hi = c["calibration_range"]
        assert lo <= hi, f"{cid}: bad calibration_range"
        assert lo == min(x) and hi == max(x), f"{cid}: calibration_range != x extent"
        assert c["hazard"] in ("flood", "wind"), f"{cid}: unexpected hazard"
        assert c["x_units"], f"{cid}: no x_units"

    assert doc["provenance"], "no provenance"
    assert doc["gaps"], "gaps list is empty -- that is itself a red flag"
    for g in doc["gaps"]:
        assert g["hazard"] and g["why"], "gap entry missing hazard or reason"

    # coverage the brief actually asked for
    jrc = [c for c in curves if c["id"].startswith("jrc_flood_")]
    continents = ["Africa", "Asia", "Europe", "North America", "Oceania", "South America"]
    for occ in ("Residential", "Commercial", "Industrial"):
        for region in continents:
            assert any(c["region"] == region and c["occupancy"] == occ for c in jrc), (
                f"missing JRC flood curve for {region}/{occ}"
            )
    assert len([c for c in curves if c["hazard"] == "wind"]) >= 10, "too few wind curves"

    from collections import Counter

    return {
        "n_curves": len(curves),
        "by_hazard": dict(Counter(c["hazard"] for c in curves)),
        "by_confidence": dict(Counter(c["confidence"] for c in curves)),
        "n_gaps": len(doc["gaps"]),
    }


def main() -> int:
    if "--check" in sys.argv:
        summary = demo()
    else:
        doc = build()
        OUT.write_text(json.dumps(doc, indent=2) + "\n")
        summary = demo(doc)
        print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")
    print("self-check PASSED:", json.dumps(summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
