def jrc_building_curves() -> list[dict]:
    src = physrisk_dir() / "EU JRC global flood depth-damage functions.json"
    items = json.loads(src.read_text())["items"]
    out = []
    for it in items:
        occ = it["asset_type"].split("/")[-1]  # Buildings/Residential -> Residential
        region = it["location"]
        if not it["impact_mean"]:
            # physrisk leaves three entries blank: Africa/Commercial and
            # Oceania/Industrial (the JRC report found no data for either and tells the
            # reader to substitute the European curve) and Global/Residential (no such
            # curve in the report). Handled explicitly below rather than filled in here.
            continue
        table = JRC_BUILDING_TABLES.get((occ, region), "continental average, section 3.2")
        x = [round(v, 4) for v in it["intensity"]]
        y = [round(v, 4) for v in it["impact_mean"]]
        conf = "high" if region in JRC_WELL_SUPPORTED else "medium"
        if region == "Global":
            conf = "medium"

        x, y, overridden = _reconcile_with_report(occ, region, x, y)
        note = (
            "values as shipped in physrisk-lib "
            "'EU JRC global flood depth-damage functions.json'; "
            "verified against the report table to 2 d.p."
        )
        if overridden:
            conf = "medium"
            note = (
                "physrisk-lib's bundled values disagreed with the published report table "
                "beyond rounding, so the report table is used here. See "
                "source_discrepancies at the top level of this file."
            )
        out.append(
            {
                "id": f"jrc_flood_{slug(region)}_{slug(occ)}",
                "hazard": "flood",
                "sub_hazard": "riverine_inundation",
                "region": region,
                "occupancy": occ,
                "damage_basis": "structure",
                "x_units": "m_inundation_depth",
                "x": x,
                "y": y,
                "source": f"{JRC_DOI}, {table}",
                "source_note": note,
                "confidence": conf,
                "calibration_range": [min(x), max(x)],
            }
        )
    out += _jrc_europe_proxies(out)
    return out


# The JRC report has no Commercial data for Africa and no Industrial data for Oceania,
# and instructs the reader to fall back on the European curve (sections 3.2.2, 3.2.3).
# Emitted so the six-continent grid is complete, but loudly flagged: same numbers as
# Europe, confidence low, proxy_for set. Not a separate empirical curve.
JRC_EUROPE_PROXY = [("Africa", "Commercial"), ("Oceania", "Industrial")]


def _jrc_europe_proxies(built: list[dict]) -> list[dict]:
    by_key = {(c["region"], c["occupancy"]): c for c in built}
    out = []
    for region, occ in JRC_EUROPE_PROXY:
        base = by_key[("Europe", occ)]
        c = dict(base)
        c["id"] = f"jrc_flood_{slug(region)}_{slug(occ)}"
        c["region"] = region
        c["confidence"] = "low"
        c["proxy_for"] = "Europe"
        c["source"] = (
            f"{JRC_DOI}: European {occ} curve applied to {region} as the report "
            f"directs, no {region} {occ} data existed"
        )
        c["source_note"] = (
            f"NOT an empirical {region} curve. Identical values to "
            f"jrc_flood_europe_{slug(occ)}. Use only as a placeholder and expect the "
            f"error to be large."
        )
        out.append(c)
    return out


