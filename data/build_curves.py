def slug(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s.lower()).strip("_")


ROUNDING_TOLERANCE = 0.02


def enforce_monotonic(curves: list[dict]) -> None:
    """Repair dips that are clearly rounding artefacts; refuse to hide anything bigger.

    physrisk rounds its terrain-averaged Hazus wind curves to 2 d.p., which can leave a
    curve stepping down by 0.01. That is noise, not physics. A running-max clamp fixes it
    and the curve is stamped monotonic_adjusted so the edit is visible in the output. A
    dip larger than the rounding tolerance is a genuine data problem and raises.
    """
    for c in curves:
        y = c["y"]
        worst = min((b - a for a, b in zip(y, y[1:])), default=0.0)
        if worst >= -1e-9:
            continue
        if worst < -ROUNDING_TOLERANCE:
            raise ValueError(
                f"{c['id']}: y drops by {abs(worst):.3f}, too large to be rounding noise"
            )
        fixed, run = [], 0.0
        for v in y:
            run = max(run, v)
            fixed.append(round(run, 4))
        c["y"] = fixed
        c["monotonic_adjusted"] = True
        c["source_note"] = (
            c.get("source_note", "")
            + f" Running-max clamp applied: the source curve stepped down by "
            f"{abs(worst):.2f}, within rounding tolerance."
        ).strip()


def fetch(name: str) -> Path:
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    path = SOURCE_DIR / name
    if not path.exists():
        print(f"downloading {name} ...", file=sys.stderr)
        urllib.request.urlretrieve(DOWNLOADS[name], path)
    return path


