# collected during build(), surfaced at the top level of the JSON
DISCREPANCIES: list[dict] = []


def _reconcile_with_report(occ: str, region: str, x: list, y: list) -> tuple[list, list, bool]:
    """Compare a physrisk curve against the published table; report table wins.

    physrisk represents the report's damage value at zero depth by placing 0.0 at 0 m and
    the published value at 0.01 m, so the depth-0 row is compared against whichever of
    those two points carries the value.
    """
    table = JRC_REPORT_TABLES.get((occ, region))
    if table is None:
        return x, y, False

    lookup = dict(zip(x, y))
    diffs = []
    for depth, published in zip(JRC_DEPTHS, table):
        got = lookup.get(0.01, lookup.get(0.0)) if depth == 0 else lookup.get(float(depth))
        if got is None:
            continue
        if abs(round(got, 2) - published) > 0.005:
            diffs.append({"depth_m": depth, "physrisk": round(got, 4), "report": published})

    if not diffs:
        return x, y, False

    curve_id = f"jrc_flood_{slug(region)}_{slug(occ)}"

    if len(diffs) == 1 and diffs[0]["depth_m"] == 0:
        # Only the zero-depth value differs: physrisk simply omitted it. Reinstate it at
        # 0.01 m, which is the convention physrisk itself uses for the other continents,
        # and keep physrisk's extra significant figures everywhere else.
        DISCREPANCIES.append(
            {
                "curve_id": curve_id,
                "issue": (
                    "physrisk-lib dropped the report's non-zero damage value at zero "
                    "depth; the rest of the curve agrees."
                ),
                "points": diffs,
                "resolution": (
                    "report value reinstated at 0.01 m, matching physrisk's own "
                    "convention on other continents; remaining points unchanged"
                ),
            }
        )
        merged = sorted(zip(x, y) if 0.01 in x else list(zip(x, y)) + [(0.01, table[0])])
        return [p[0] for p in merged], [p[1] for p in merged], False

    DISCREPANCIES.append(
        {
            "curve_id": curve_id,
            "issue": (
                "physrisk-lib's bundled JRC values disagree with the published report "
                "table beyond rounding. Resolved in favour of the report, which is what "
                "the curve cites."
            ),
            "points": diffs,
            "resolution": "report table values used; confidence downgraded to medium",
        }
    )
    return list(JRC_DEPTHS), list(table), True


