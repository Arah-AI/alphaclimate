def _strip(d):
    out = json.loads(json.dumps(d))
    out["provenance"].pop("computed_at", None)
    for row in out.get("yearly", []):
        row.pop("year", None)
    for row in out.get("impairment_path", []):
        row.pop("year", None)
    return out


@invariant("DET-REPEAT", "determinism", "the same inputs give the same answer")
def _(c):
    assert _strip(c.summ) == _strip(c.summ_repeat), (
        "two identical runs produced different output")
    assert c.summ["provenance"]["run_id"] == c.summ_repeat["provenance"]["run_id"], (
        "run id is not stable across identical runs")
    return "byte-identical across two runs"


@invariant("DET-ORDER", "determinism", "asset order cannot change the answer")
def _(c):
    a, b = c.summ["headline"], c.summ_reversed["headline"]
    assert a == b, "reversing the portfolio changed the headline"
    ra = sorted(c.summ["assets"], key=lambda r: r["id"])
    rb = sorted(c.summ_reversed["assets"], key=lambda r: r["id"])
    assert ra == rb, "reversing the portfolio changed the asset rows"
    return "headline and rows identical under reversal"


@invariant("DET-RUNID", "determinism", "the run id is a function of its inputs")
def _(c):
    before = c.summ["provenance"]["run_id"]
    after = c.summ_mutated["provenance"]["run_id"]
    assert before != after, (
        "changing an asset's value from {:,.0f} to 1 left the run id at {}. A "
        "provenance id that does not move when the portfolio moves is not a "
        "provenance id".format(c.assets[0].value, before))
    return "run id moves when the portfolio moves"


@invariant("DET-SCENARIO", "determinism", "a hotter scenario is never cheaper")
def _(c):
    bad = []
    r126 = {r["id"]: r["eal"] for r in c.summ_126["assets"]}
    r245 = {r["id"]: r["eal"] for r in c.summ_245["assets"]}
    r585 = {r["id"]: r["eal"] for r in c.summ["assets"]}
    for aid in r585:
        hot, mid, cool = r585[aid], r245.get(aid, 0.0), r126.get(aid, 0.0)
        if hot < mid - 1e-6 or mid < cool - 1e-6:
            bad.append("{} 126={:,.0f} 245={:,.0f} 585={:,.0f}".format(
                aid, cool, mid, hot))
    assert not bad, "scenario ordering violated: " + ", ".join(bad[:3])
    h126 = c.summ_126["headline"]["eal"]
    h585 = c.summ["headline"]["eal"]
    assert h585 >= h126 - 1e-6, "ssp585 portfolio is cheaper than ssp126"
    return "ssp585 >= ssp245 >= ssp126 on every asset and at portfolio level"


