@invariant("VUL-OVERLAP", "vulnerability", "an asset cannot be destroyed twice")
def _(c):
    worst, where = 0.0, ""
    for a in c.assets:
        prs = c.event_perils[a.id]
        if len(prs) < 2:
            continue
        grid = sorted({r for pr in prs for r in pr.lc.return_periods})
        for rp in grid:
            tot = sum(frac_at_rp(pr, rp) for pr in prs)
            if tot > worst:
                worst, where = tot, "{} at 1-in-{:g}".format(a.id, rp)
    assert worst <= 1.0 + 1e-9, (
        "combined damage fraction reaches {:.3f} ({}): overlapping perils are "
        "summed, so the asset is destroyed {:.2f} times".format(worst, where, worst))
    return "combined damage fraction peaks at {:.3f}".format(worst)


@invariant("VUL-MDF", "vulnerability",
           "the outage driver is an annual expectation, not a peak")
def _(c):
    bad = []
    for a in c.assets:
        for r in c.event_perils[a.id]:
            if r.lc.eal <= 0:
                continue
            expected = r.lc.eal / a.value if a.value else 0.0
            got = r.mean_damage_fraction
            if abs(got - expected) > 1e-9 * max(1e-12, expected):
                bad.append("{}/{} {:.4f} vs {:.6f}".format(a.id, r.peril, got, expected))
    assert not bad, (
        "{} peril results disagree with their own docstring (it claims the EAL "
        "as a share of value): {}".format(len(bad), ", ".join(bad[:4])))
    return "mean damage fraction equals EAL / value on every curve"


@invariant("VUL-BI", "vulnerability",
           "a loss-making asset has non-zero business interruption")
def _(c):
    from app.finance import translate
    for a in c.assets:
        e = c.eal_of(a.id)
        if e <= 0 or a.annual_revenue <= 0:
            continue
        mdf = max((r.mean_damage_fraction for r in c.event_perils[a.id]), default=0.0)
        f = translate(e, mdf, c.fin_for(a), c.assumptions)
        assert f.annual_business_interruption > 0, (
            "{} loses {:,.0f} a year but reports zero business interruption"
            .format(a.id, e))
        days = min(365.0, mdf * c.assumptions.downtime_days_per_damage_unit)
        assert 0 < days <= 365, "{}: downtime {:.1f} days outside (0, 365]".format(a.id, days)
    return "every exposed revenue-earning asset has positive outage cost"


