@invariant("INS-PAYS", "insurance", "a programme with recoverable events pays out")
def _(c):
    from app.finance import translate
    silent = []
    for a in c.assets:
        prs = c.event_perils[a.id]
        e = c.eal_of(a.id)
        if e <= 0:
            continue
        worst_event = max((max(r.lc.losses) for r in prs if r.lc.losses), default=0.0)
        if worst_event <= INS["deductible_fraction"] * a.value:
            continue
        mdf = max((r.mean_damage_fraction for r in prs), default=0.0)
        f = translate(e, mdf, c.fin_for(a), c.assumptions)
        if f.annual_insurance_recovery <= 0:
            silent.append("{} (worst event {:,.0f} > deductible {:,.0f}, premium {:,.0f})"
                          .format(a.id, worst_event,
                                  INS["deductible_fraction"] * a.value, f.annual_premium))
    assert not silent, (
        "{} assets have recoverable events yet recover nothing while still "
        "paying premium: {}. A per-event deductible is being subtracted from "
        "an annual expectation".format(len(silent), "; ".join(silent[:3])))
    return "every asset with recoverable events receives a recovery"


@invariant("INS-BOUNDED", "insurance", "recovery cannot exceed the loss or the cover")
def _(c):
    from app.finance import translate
    cap_f = INS["limit_fraction"] * (1.0 - INS["coinsurance"])
    for a in c.assets:
        e = c.eal_of(a.id)
        if e <= 0:
            continue
        mdf = max((r.mean_damage_fraction for r in c.event_perils[a.id]), default=0.0)
        f = translate(e, mdf, c.fin_for(a), c.assumptions)
        rec = f.annual_insurance_recovery
        assert rec >= -1e-9, "{}: negative recovery".format(a.id)
        assert rec <= e + 1e-6, (
            "{}: recovery {:,.0f} exceeds expected annual loss {:,.0f}".format(a.id, rec, e))
        assert rec <= cap_f * a.value + 1e-6, (
            "{}: recovery {:,.0f} exceeds the cover cap {:,.0f}"
            .format(a.id, rec, cap_f * a.value))
    return "recovery bounded by both the loss and the programme limit"


@invariant("INS-MONO-DED", "insurance", "a higher deductible never recovers more")
def _(c):
    from app.finance import Assumptions, translate
    a = max(c.assets, key=lambda x: c.eal_of(x.id))
    e = c.eal_of(a.id)
    assert e > 0, "no asset carries a loss to insure"
    mdf = max((r.mean_damage_fraction for r in c.event_perils[a.id]), default=0.0)
    prev, seq = None, []
    for d in (0.0, 0.005, 0.02, 0.05, 0.2, 0.6):
        opts = dict(INS)
        opts["deductible_fraction"] = d
        f = translate(e, mdf, c.fin_for(a), Assumptions(**opts))
        seq.append(f.annual_insurance_recovery)
        if prev is not None:
            assert f.annual_insurance_recovery <= prev + 1e-6, (
                "raising the deductible to {:.1%} raised recovery".format(d))
        prev = f.annual_insurance_recovery
    return "recovery falls monotonically as the deductible rises"


@invariant("INS-RECONCILE", "insurance", "the insurance headline reconciles")
def _(c):
    h = c.summ["headline"]
    ins, ret = h["insured_share"], h["retained_share"]
    assert abs(ins + ret - 1.0) <= 1e-4, (
        "insured {:.4f} + retained {:.4f} != 1".format(ins, ret))
    assert ins <= 1.0 + 1e-9, "insured share above 1: the clamp is doing real work"
    gap, eal = h["protection_gap"], h["eal"]
    assert abs(gap - eal * (1.0 - ins)) <= max(1.0, 1e-4 * eal), (
        "protection gap {:,.0f} does not equal EAL x retained share {:,.0f}"
        .format(gap, eal * (1.0 - ins)))
    return "insured {:.1%}, retained {:.1%}, gap reconciles".format(ins, ret)


