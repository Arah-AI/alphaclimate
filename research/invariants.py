def git(*args):
    try:
        return subprocess.run(["git"] + list(args), capture_output=True, text=True,
                              cwd=os.path.dirname(os.path.abspath(__file__)),
                              timeout=15).stdout.strip()
    except Exception:
        return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--experiment", type=int, default=None)
    args = ap.parse_args()

    t0 = time.time()
    here = os.path.abspath(__file__)
    result = {
        "schema": 1,
        "experiment": args.experiment,
        "git_sha": git("rev-parse", "HEAD"),
        "git_subject": git("log", "-1", "--format=%s"),
        "eval_sha256": hashlib.sha256(open(here, "rb").read()).hexdigest()[:16],
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }

    try:
        ctx = Ctx()
    except Exception as e:
        result.update({
            "score": 0, "total": len(_REG), "checks": [],
            "duration_s": round(time.time() - t0, 2),
            "aborted": "{}: {}".format(type(e).__name__, e)[:400],
        })
        print(json.dumps(result, indent=2))
        return

    checks = []
    for inv_id, group, name, fn in _REG:
        t = time.time()
        try:
            detail, held = (fn(ctx) or ""), True
        except AssertionError as e:
            detail, held = str(e), False
        except Exception as e:
            detail, held = "ERROR: {}: {}".format(type(e).__name__, e), False
        checks.append({
            "name": inv_id, "group": group, "title": name, "held": held,
            "detail": detail[:400],
            "duration_ms": round((time.time() - t) * 1000, 1),
        })

    h = ctx.summ["headline"]
    by_group = {}
    for ch in checks:
        g = by_group.setdefault(ch["group"], [0, 0])
        g[1] += 1
        if ch["held"]:
            g[0] += 1

    result.update({
        "score": sum(1 for ch in checks if ch["held"]),
        "total": len(checks),
        "duration_s": round(time.time() - t0, 2),
        "aborted": None,
        "by_group": by_group,
        "headline": {
            "eal": h["eal"],
            "eal_pct_of_value": h["eal_pct_of_value"],
            "npv_climate_cost": h["npv_climate_cost"],
            "insured_share": h["insured_share"],
            "spread_n": h["eal_spread"]["n"],
            "covenant_breaches": h["covenant_breaches"],
        },
        "checks": checks,
    })
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
