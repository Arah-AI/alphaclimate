@invariant("AGG-SUM", "coherence", "the whole equals the sum of its parts")
def _(c):
    h = c.summ["headline"]
    rows = c.summ["assets"]
    tot = sum(r["eal"] for r in rows)
    assert abs(tot - h["eal"]) <= max(1.0, 1e-6 * h["eal"]), (
        "headline EAL {:,.0f} != sum of rows {:,.0f}".format(h["eal"], tot))
    shares = sum(p["share"] for p in c.summ["perils"])
    assert abs(shares - 1.0) <= 1e-3, "peril shares sum to {:.4f}".format(shares)
    assert sum(h["bands"].values()) == h["asset_count"], "bands do not cover every asset"
    return "rows, peril shares and bands all reconcile"


@invariant("AGG-IN-SWEEP", "coherence", "the headline is a member of its own sweep")
def _(c):
    h = c.summ["headline"]
    sp = h["eal_spread"]
    assert sp["low"] <= h["eal"] <= sp["high"], (
        "headline {:,.0f} outside its spread {:,.0f}-{:,.0f}"
        .format(h["eal"], sp["low"], sp["high"]))
    assert c.sweep, "the sweep produced no values"
    closest = min(c.sweep, key=lambda v: abs(v - h["eal"]))
    rel = abs(closest - h["eal"]) / h["eal"] if h["eal"] else 0.0
    assert rel <= 1e-6, (
        "no sweep point matches the headline; nearest is {:,.0f} vs {:,.0f} "
        "({:.2%} off): the sweep and the headline are different models"
        .format(closest, h["eal"], rel))
    return "headline matches a sweep point exactly and sits inside the range"


@invariant("SWEEP-DISTINCT", "coherence", "every sweep point is a distinct model")
def _(c):
    n = len(c.sweep)
    distinct = len({sig(v) for v in c.sweep})
    assert distinct == n, (
        "{} sweep points carry only {} distinct values: duplicated model "
        "configurations are biasing the median and inflating n"
        .format(n, distinct))
    return "{} sweep points, all distinct".format(n)


@invariant("SWEEP-NONDEGEN", "coherence", "real disagreement survives the sweep")
def _(c):
    sp = c.summ["headline"]["eal_spread"]
    assert sp["n"] >= MIN_SWEEP_POINTS, (
        "sweep collapsed to {} points, below the {} floor".format(sp["n"], MIN_SWEEP_POINTS))
    ratio = sp["high"] / sp["low"] if sp["low"] > 0 else 0.0
    assert ratio >= MIN_SWEEP_RANGE_RATIO, (
        "high/low is {:.2f}, below the {:.1f} floor: the models no longer disagree"
        .format(ratio, MIN_SWEEP_RANGE_RATIO))
    return "n={}, high/low {:.2f}".format(sp["n"], ratio)


@invariant("BAND-CONSISTENT", "coherence", "risk bands match the numbers they label")
def _(c):
    for r in c.summ["assets"]:
        want = c.compute.band_for(r["eal_pct"])
        assert r["band"] == want, (
            "{}: banded {} at {:.4%}, should be {}".format(
                r["id"], r["band"], r["eal_pct"], want))
    occupied = sum(1 for v in c.summ["headline"]["bands"].values() if v)
    assert occupied >= 2, "every asset landed in one band; the banding is not discriminating"
    return "{} bands occupied, every row correctly labelled".format(occupied)


