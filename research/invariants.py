@invariant("INT-DOMAIN", "integration",
           "expected loss integrates the full probability domain")
def _(c):
    from app.engine import loss_curve
    lc = loss_curve(FIXTURE_RPS, FIXTURE_INTS, FIXTURE_X, FIXTURE_Y, FIXTURE_VALUE)
    ref = ref_eal(lc.return_periods, lc.losses)
    assert abs(lc.eal - ref) <= 1e-9 * ref, (
        "fixture: eal {:,.0f} vs reference {:,.0f} ({:+.2%}); the probability "
        "band p in [{:.3f}, 1.0] carries no loss".format(
            lc.eal, ref, lc.eal / ref - 1.0, 1.0 / lc.return_periods[0])
    )
    bad = []
    for aid, prs in c.event_perils.items():
        for r in prs:
            ref = ref_eal(r.lc.return_periods, r.lc.losses)
            if ref > 0 and abs(r.lc.eal - ref) > 1e-9 * ref:
                bad.append("{}/{} {:+.1%}".format(aid, r.peril, r.lc.eal / ref - 1.0))
    assert not bad, "live curves understate: " + ", ".join(bad[:4])
    return "fixture and {} live curves match the reference integral".format(
        sum(len(v) for v in c.event_perils.values()))


@invariant("INT-STEP", "integration",
           "a flood defence is a discontinuity, not a ramp")
def _(c):
    from app import protection as prot
    from app.engine import loss_curve
    worst, worst_id = 0.0, ""
    for a in c.assets:
        for r in c.event_perils[a.id]:
            p = prot.sop(a.lon, a.lat, r.peril)
            if not p:
                continue
            rr, ii = with_step_knot(r.reading.return_periods, r.reading.intensities, p)
            if len(rr) == len(r.reading.return_periods):
                continue
            ref = loss_curve(rr, ii, r.curve["x"], r.curve["y"], a.value,
                             r.curve.get("calibration_range"), p).eal
            if ref > 0:
                err = abs(r.lc.eal - ref) / ref
                if err > worst:
                    worst, worst_id = err, "{}/{} {:,.0f} vs {:,.0f}".format(
                        a.id, r.peril, r.lc.eal, ref)
    assert worst <= 0.02, (
        "worst defended curve is {:.1%} off the knotted reference: {}. The "
        "trapezoid spanning the standard carries half a step of held-back loss"
        .format(worst, worst_id))
    return "every defended curve within 2% of its knotted reference"


def _refined_peril_eal(c, a, r, factor):
    from app import protection as prot
    from app.engine import loss_curve
    rr, ii = refine(r.reading.return_periods, r.reading.intensities, factor)
    return loss_curve(rr, ii, r.curve["x"], r.curve["y"], a.value,
                      r.curve.get("calibration_range"),
                      prot.sop(a.lon, a.lat, r.peril)).eal


@invariant("INT-CONVERGE-PF", "integration",
           "portfolio loss is converged on the modelled grid")
def _(c):
    coarse = sum(c.eal_of(a.id) for a in c.assets)
    fine = sum(_refined_peril_eal(c, a, r, 32)
               for a in c.assets for r in c.event_perils[a.id])
    assert coarse > 0, "portfolio EAL is zero"
    drift = fine / coarse - 1.0
    assert abs(drift) <= 0.02, (
        "refining the return-period grid 32x moves portfolio EAL {:+.2%} "
        "({:,.0f} to {:,.0f}); the 9-point trapezoid is not converged"
        .format(drift, coarse, fine))
    return "portfolio EAL moves {:+.2%} under 32x refinement".format(drift)


