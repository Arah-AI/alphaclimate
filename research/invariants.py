def ref_eal(rps, losses):
    """Expected annual loss by trapezoid over exceedance probability.

    The probability domain is [0, 1]. Anchored at p = 1 with zero loss, which
    is the assumption "events more frequent than the shortest modelled return
    period cause no damage". Flat tail beyond the longest return period.
    """
    ps = [1.0 / r for r in rps]
    total = 0.5 * losses[0] * (1.0 - ps[0])
    for i in range(len(ps) - 1):
        total += 0.5 * (losses[i] + losses[i + 1]) * (ps[i] - ps[i + 1])
    return total + losses[-1] * ps[-1]


def intensity_at(rps, ints, r):
    """Intensity at an arbitrary return period, interpolated in log-RP space.

    Same rule the engine already uses in loss_at_return_period.
    """
    if r <= rps[0]:
        return ints[0]
    if r >= rps[-1]:
        return ints[-1]
    for j in range(1, len(rps)):
        if r <= rps[j]:
            l0, l1 = math.log(rps[j - 1]), math.log(rps[j])
            t = (math.log(r) - l0) / (l1 - l0)
            return ints[j - 1] + t * (ints[j] - ints[j - 1])
    return ints[-1]


def refine(rps, ints, factor):
    """Subdivide every RP interval `factor` times, geometrically."""
    out_r, out_i = [], []
    for i in range(len(rps) - 1):
        for k in range(factor):
            f = k / float(factor)
            r = math.exp(math.log(rps[i]) + f * (math.log(rps[i + 1]) - math.log(rps[i])))
            out_r.append(r)
            out_i.append(intensity_at(rps, ints, r))
    out_r.append(rps[-1])
    out_i.append(ints[-1])
    return out_r, out_i


def with_step_knot(rps, ints, protection_rp):
    """Insert a zero-loss knot immediately below the protection standard.

    A defence built to a 1-in-N standard is a discontinuity. Without a knot at
    N the trapezoid spanning it carries half a step of loss that the defence
    is supposed to hold back.
    """
    if not protection_rp or protection_rp <= rps[0] or protection_rp >= rps[-1]:
        return list(rps), list(ints)
    k = protection_rp * (1.0 - 1e-9)
    pairs = sorted(zip(list(rps) + [k], list(ints) + [intensity_at(rps, ints, k)]))
    return [p[0] for p in pairs], [p[1] for p in pairs]


def frac_at_rp(pr, r):
    """Damage fraction of one peril result at an arbitrary return period."""
    rps, fr = pr.lc.return_periods, pr.lc.damage_fractions
    if not rps:
        return 0.0
    if r <= rps[0]:
        return fr[0]
    if r >= rps[-1]:
        return fr[-1]
    for j in range(1, len(rps)):
        if r <= rps[j]:
            l0, l1 = math.log(rps[j - 1]), math.log(rps[j])
            t = (math.log(r) - l0) / (l1 - l0)
            return fr[j - 1] + t * (fr[j] - fr[j - 1])
    return fr[-1]


def sig(x, digits=6):
    """Round to significant figures, for distinctness tests."""
    if x == 0:
        return 0.0
    return round(x, -int(math.floor(math.log10(abs(x)))) + (digits - 1))


