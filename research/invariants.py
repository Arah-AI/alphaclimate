class Ctx:
    def __init__(self):
        from app import compute, portfolio as pf
        from app.finance import Assumptions

        self.compute = compute
        self.pf = pf
        self.assumptions = Assumptions(**INS)

        self.assets = list(pf.DEMO_ASSETS)
        self.summ = compute.summary(SCENARIO)
        self.summ_126 = compute.summary("ssp126")
        self.summ_245 = compute.summary("ssp245")

        # Per-asset peril results, event perils only (permanent inundation is a
        # write-down, not an annual loss, and summary() excludes it too).
        self.perils = {}
        self.event_perils = {}
        for a in self.assets:
            prs = compute._asset_perils(a, SCENARIO)
            self.perils[a.id] = prs
            self.event_perils[a.id] = [r for r in prs if not r.permanent]

        self.by_id = {a.id: a for a in self.assets}
        self.rows = {r["id"]: r for r in self.summ["assets"]}

        # The raw sweep, recomputed here so distinctness and membership can be
        # tested. portfolio_spread() returns only the summary statistics.
        self.sweep = self._sweep()

        # Determinism probes. Each restores DEMO_ASSETS before returning.
        self.summ_repeat = compute.summary(SCENARIO)
        self.summ_reversed = self._with_assets(list(reversed(self.assets)))
        self.summ_doubled = self._with_assets(self._doubled(self.assets))
        self.summ_mutated = self._with_assets(self._mutated(self.assets))

    def _sweep(self):
        c, pf = self.compute, self.pf
        from app import hazard as hz
        vals = []
        n_variants = max((len(hz.variants(p)) for p in hz.PERILS), default=1)
        for sc in c.SPREAD_SCENARIOS:
            for vrank in range(max(1, n_variants)):
                for crank in range(3):
                    total = sum(c._asset_eal(a, sc, vrank, crank) for a in self.assets)
                    if total <= 0:
                        continue
                    vals.append(total)
        return vals

    def _with_assets(self, assets):
        pf = self.pf
        original = pf.DEMO_ASSETS
        try:
            pf.DEMO_ASSETS = assets
            return self.compute.summary(SCENARIO)
        finally:
            pf.DEMO_ASSETS = original

    @staticmethod
    def _doubled(assets):
        out = []
        for a in assets:
            b = copy.copy(a)
            b.value = a.value * 2
            b.annual_revenue = a.annual_revenue * 2
            b.debt = a.debt * 2
            b.annual_debt_service = a.annual_debt_service * 2
            out.append(b)
        return out

    @staticmethod
    def _mutated(assets):
        out = [copy.copy(a) for a in assets]
        out[0].value = 1.0
        return out

    def fin_for(self, asset):
        from app.finance import AssetFinancials
        return AssetFinancials(
            value=asset.value,
            annual_revenue=asset.annual_revenue,
            debt=asset.debt,
            annual_debt_service=asset.annual_debt_service,
        )

    def eal_of(self, asset_id):
        return sum(r.lc.eal for r in self.event_perils[asset_id])


